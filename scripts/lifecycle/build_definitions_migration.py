#!/usr/bin/env python3
"""Write db/migrations/033_document_columns.sql: COMMENT ON COLUMN for every column that has none.

Text comes from definitions_manual.py where a person wrote it, else from propose_definitions' fact-based rules.
Columns covered by neither are listed and the script exits 1. A nullable column's text must say what NULL means.
Usage: python3 scripts/lifecycle/build_definitions_migration.py [out.sql]     (reads PG* variables)
"""
import os, subprocess, sys
import psycopg2
sys.path.insert(0, os.path.dirname(__file__))
from definitions_manual import D

here = os.path.dirname(os.path.abspath(__file__))
out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "db", "migrations", "033_document_columns.sql")
tsv = subprocess.run([sys.executable, os.path.join(here, "propose_definitions.py")], capture_output=True, text=True, check=True).stdout
cx = psycopg2.connect(host=os.getenv("PGHOST", "127.0.0.1"), port=os.getenv("PGPORT", "5432"), user=os.getenv("PGUSER", "talentra_admin"),
                      dbname=os.getenv("PGDATABASE", "talentra"), password=os.getenv("PGPASSWORD"))
cur = cx.cursor()
lines, missing, bad = [], [], []
for row in tsv.splitlines():
    rel, col, typ, nul, rule, auto = row.split("\t")
    key = f"{rel}.{col}"
    text = D.get(key)
    if text is None and key in D:      # placeholder: same meaning as the unpartitioned original, built earlier in this run
        base = key.replace("_partitioned", "")
        text = next((x[2] for x in lines if f"{x[0]}.{x[1]}" == base), None)
    if not text: text = auto
    if not text: missing.append(key); continue
    if nul == "NULL" and "NULL" not in text:
        if rule in ("fallback", ) or key in D: bad.append(key)
        text += " NULL when not recorded."
    lines.append((rel, col, text))
if not lines:
    sys.exit("nothing to define: run this on a database built from migrations 001-032 only (033 already applied)")
if missing or bad:
    print("no definition:", *missing, sep="\n  ", file=sys.stderr)
    print("nullable without a statement of what NULL means:", *bad, sep="\n  ", file=sys.stderr)
    sys.exit(1)
body = ["-- 033: column definitions (docket B: every column has a definition; nullable columns say why).",
        "-- Generated by scripts/lifecycle/build_definitions_migration.py from facts in the database plus hand-written text.", "BEGIN;", ""]
cur_rel = None
for rel, col, text in lines:
    if rel != cur_rel: body.append(f"\n-- {rel}"); cur_rel = rel
    body.append(f"COMMENT ON COLUMN {rel}.{col} IS '{text.replace(chr(39), chr(39)*2)}';")
# earlier migrations commented these without saying what NULL means; complete them here
AMEND = {
 "profile.candidate_profile.professional_summary": "Candidate-provided professional summary; treat as personal data. NULL until the candidate writes one.",
 "recruitment.job_posting.salary_min": "Lower compensation bound; requires currency and salary period when supplied. NULL when the job discloses no salary.",
 "recruitment.job_posting.salary_max": "Upper compensation bound; requires currency and salary period when supplied. NULL when the job discloses no salary.",
 "profile.course_enrolment.completed_at": "Set if and only if the status is completed. NULL until the course is completed.",
}
body.append("\n-- amended: earlier text plus what NULL means")
for k, v in AMEND.items():
    body.append(f"COMMENT ON COLUMN {k} IS '{v}';")
body += ["", "COMMIT;", ""]
open(out_path, "w").write("\n".join(body))
print(f"{len(lines)} definitions -> {out_path}")
