#!/usr/bin/env python3
"""Generate docs/phase-1-discover/05-audit-event-matrix.md from the live database (playbook step 05, docket Rule Group 10 / B79).

Everything in the matrix is read from the catalogue, not typed: action codes and their trail from audit.action_catalogue,
the writing mechanism from pg_trigger and pg_proc, the structural limits of audit_event from pg_constraint / pg_attribute.
Usage: python3 scripts/lifecycle/gen_audit_matrix.py     (reads PG* variables)
"""
import os, re
import psycopg2

CLASSES = {1: "Session creation (successful login)", 2: "Authentication failure", 3: "Session revocation", 4: "Device entitlement breach",
           5: "Credential change", 6: "Role or permission assignment change", 7: "Account status change", 8: "Administrative impersonation",
           9: "Consent grant or withdrawal", 10: "Block or unblock of a user or organisation", 11: "Candidate profile view, unlock or download",
           12: "Application stage change", 13: "Wallet transaction", 14: "Payment, refund or licence change"}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "docs", "phase-1-discover", "05-audit-event-matrix.md")


def main():
    cx = psycopg2.connect(host=os.getenv("PGHOST", "127.0.0.1"), port=os.getenv("PGPORT", "5432"), user=os.getenv("PGUSER", "talentra_admin"),
                          dbname=os.getenv("PGDATABASE", "talentra"), password=os.getenv("PGPASSWORD"))
    cur = cx.cursor()
    cur.execute("SELECT sensitive_class, code, trail, trail_table, description FROM audit.action_catalogue ORDER BY 1, 2")
    actions = cur.fetchall()
    cur.execute("""SELECT t.tgrelid::regclass::text, t.tgname FROM pg_trigger t JOIN pg_proc p ON p.oid = t.tgfoid JOIN pg_namespace n ON n.oid = p.pronamespace
                    WHERE NOT t.tgisinternal AND n.nspname = 'audit' AND p.proname = 'log_change' ORDER BY 1""")
    log_change = cur.fetchall()
    cur.execute("""SELECT p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                    WHERE n.nspname = 'core' AND p.prokind IN ('f','p') AND pg_get_functiondef(p.oid) ILIKE '%INSERT INTO audit.audit_event%' ORDER BY 1""")
    writers = [r[0] for r in cur.fetchall()]
    tests = sorted(f for f in os.listdir(os.path.join(os.path.dirname(OUT), "..", "..", "tests")) if f == "test_audit_coverage.sql")
    cur.execute("SELECT count(*) FROM audit.sensitive_class_coverage WHERE action_codes = 0"); uncovered = cur.fetchone()[0]
    cur.execute("SELECT count(*), count(*) FILTER (WHERE trail = 'audit_event'), count(*) FILTER (WHERE trail = 'domain_ledger') FROM audit.action_catalogue")
    n_codes, n_ae, n_dl = cur.fetchone()
    # structural properties of audit.audit_event, each read from the catalogue
    cur.execute("SELECT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='audit' AND table_name='audit_event' AND column_name='organization_id')"); has_org = cur.fetchone()[0]
    cur.execute("SELECT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='audit.audit_event'::regclass AND contype='f' AND confrelid='audit.action_catalogue'::regclass)"); has_vocab = cur.fetchone()[0]
    cur.execute("SELECT string_agg(DISTINCT confdeltype::text, ',') FROM pg_constraint WHERE conrelid='audit.audit_event'::regclass AND contype='f' AND conname LIKE '%actor%'"); actor_del = cur.fetchone()[0]
    cur.execute("SELECT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='audit.audit_event'::regclass AND NOT tgisinternal AND (tgtype & 32) = 32)"); trunc = cur.fetchone()[0]
    cur.execute("SELECT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='audit.system_error_log'::regclass AND NOT tgisinternal AND tgfoid::regproc::text ~ 'prevent')"); err_guard = cur.fetchone()[0]
    cur.execute("SELECT EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='audit' AND c.relname='org_audit_event')"); org_view = cur.fetchone()[0]
    cur.execute("SELECT EXISTS (SELECT 1 FROM pg_class WHERE oid='audit.audit_event'::regclass AND relrowsecurity)"); rls = cur.fetchone()[0]

    by_class = {}
    for cl, code, trail, tbl, desc in actions:
        by_class.setdefault(cl, []).append((code, trail, tbl, desc))
    L = ["# Audit Event Matrix", "",
         "**Phase 1, step 5.** Generated by `scripts/lifecycle/gen_audit_matrix.py` from the migrated database; do not edit by hand. Re-run `scripts/lifecycle/regenerate.sh`.", "",
         "The docket (Rule Group 10, B79) names 14 classes of sensitive action. For each: which action codes exist, where the record is written, and whether the trail names who, what and when. "
         "`tests/test_audit_coverage.sql` performs every class and checks the record, then checks what the record must not contain (secrets, hashes).", "",
         f"**Result:** {14 - uncovered} of 14 classes have at least one catalogued action; {n_codes} action codes ({n_ae} written to `audit.audit_event`, {n_dl} evidenced by a domain ledger that is itself append-only).", "",
         "## 1. Coverage by class", "", "| # | Sensitive action | Action code | Recorded in | Meaning |", "|--:|:--|:--|:--|:--|"]
    for cl in range(1, 15):
        for i, (code, trail, tbl, desc) in enumerate(by_class.get(cl, [("-", "-", None, "NOT CATALOGUED")])):
            where = f"`{tbl}` (append-only ledger)" if trail == "domain_ledger" else ("`audit.audit_event`" if trail == "audit_event" else "-")
            L.append(f"| {cl if i == 0 else ''} | {CLASSES[cl] if i == 0 else ''} | `{code}` | {where} | {desc} |")
    L += ["", "## 2. How events get written", "",
          "Row triggers call `audit.log_change()` on these tables, so a change cannot be made without leaving the record:", "",
          "| Table | Trigger |", "|:--|:--|"] + [f"| `{t}` | `{g}` |" for t, g in log_change]
    L += ["", "Functions that write `audit.audit_event` themselves (they know more than a row trigger can: outcome, device, reason): "
          + ", ".join(f"`core.{w}`" for w in writers) + ".", "",
          "## 3. Properties of the audit table (read from the catalogue)", "", "| Property | Now | Why it matters |", "|:--|:--|:--|",
          f"| Tenant column `organization_id` | {'yes' if has_org else '**no**'} | An organisation administrator can be shown their own events only"
          f"{' (view `audit.org_audit_event`)' if org_view else ''} |",
          f"| Action must exist in the catalogue | {'yes (foreign key)' if has_vocab else '**no**'} | A misspelt action code cannot be written, so coverage can be counted |",
          f"| Actor foreign keys | {'ON DELETE RESTRICT' if actor_del == 'r' else 'ON DELETE ' + str(actor_del)} | An actor with history cannot be deleted; erasure anonymises instead |",
          f"| TRUNCATE blocked | {'yes' if trunc else '**no**'} | A row trigger does not fire on TRUNCATE |",
          f"| Updates and deletes refused | yes (`audit.prevent_modification`) | The trail is evidence |",
          f"| Row-level security | {'yes' if rls else 'no (grants only)'} | Who may read the trail |",
          f"| `audit.system_error_log` tamper guard | {'yes' if err_guard else '**no**'} | Operational errors are the least protected log |", "",
          "## 4. Known limits", "",
          "- `entity_id` is a single `BIGINT`; an action on a table with a composite key records the surrogate id only.",
          "- Payload columns (`old_values_json`, `new_values_json`) are not indexed; searching them scans. Search by actor, action, entity or time instead (indexed).",
          "- Domain ledgers (profile view, download, application stage, wallet) evidence classes 11 to 13 with actor and time but without client address; DEC-14 in `docs/lifecycle/decision-log.md` records why.",
          f"- Executed by: {', '.join('`tests/' + t + '`' for t in tests)}.", ""]
    open(OUT, "w").write("\n".join(L))
    print(f"wrote {os.path.relpath(OUT)}: {n_codes} codes, {len(log_change)} audit triggers, {len(writers)} writing functions, uncovered classes {uncovered}")


if __name__ == "__main__":
    main()
